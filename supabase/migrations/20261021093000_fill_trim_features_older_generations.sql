    JOIN catalog_phases p ON p.id = t.phase_id JOIN catalog_models m ON m.id = p.model_id
    JOIN (SELECT DISTINCT model, gen, phase, trim_name FROM _trim_fill) f
      ON m.name = f.model AND p.generation_code = f.gen AND p.phase_label = f.phase AND t.name = f.trim_name
    WHERE EXISTS (SELECT 1 FROM catalog_trim_features cf WHERE cf.trim_id = t.id);
  IF busy <> 0 THEN RAISE EXCEPTION '% target trim(s) already have features', busy; END IF;
END $$;

INSERT INTO catalog_trim_features (trim_id, feature, is_optional)
SELECT t.id, f.feature, f.is_optional
FROM _trim_fill f
JOIN catalog_models m ON m.name = f.model
JOIN catalog_phases p ON p.model_id = m.id AND p.generation_code = f.gen AND p.phase_label = f.phase
JOIN catalog_trims t ON t.phase_id = p.id AND t.name = f.trim_name;

DO $$
DECLARE left_empty integer;
BEGIN
  SELECT count(*) INTO left_empty FROM catalog_trims t
  WHERE NOT EXISTS (SELECT 1 FROM catalog_trim_features cf WHERE cf.trim_id = t.id);
  IF left_empty <> 0 THEN RAISE EXCEPTION '% trims still without features', left_empty; END IF;
END $$;

COMMIT;
