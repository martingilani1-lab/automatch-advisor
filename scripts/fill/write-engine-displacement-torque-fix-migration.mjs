// Writes the guarded, review-only migration filling missing catalog_engines.displacement_cc
// (18 engines) and torque_nm (1 engine, ARY@132), NULL-only. Writes a file only -- never
// executes anything against the DB.

import { createClient } from "@supabase/supabase-js";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const supabase = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY
);

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const MIGRATIONS_DIR = path.join(__dirname, "..", "..", "supabase", "migrations");

function tsNow() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, "0");
  return `${d.getUTCFullYear()}${p(d.getUTCMonth() + 1)}${p(d.getUTCDate())}${p(d.getUTCHours())}${p(d.getUTCMinutes())}${p(d.getUTCSeconds())}`;
}

const DISPLACEMENT_TARGETS = [
  { code: "AGZ", kw: 110, cc: 2324 }, { code: "AQN", kw: 125, cc: 2324 },
  { code: "AJM", kw: 85, cc: 1896 }, { code: "ARL", kw: 110, cc: 1896 }, { code: "BSW", kw: 77, cc: 1896 },
  { code: "APG", kw: 92, cc: 1781 }, { code: "AMK", kw: 154, cc: 1781 }, { code: "APY", kw: 154, cc: 1781 },
  { code: "BAM", kw: 165, cc: 1781 }, { code: "BFV", kw: 176, cc: 1781 }, { code: "BVP", kw: 120, cc: 1781 },
  { code: "BVR", kw: 140, cc: 1781 }, { code: "ARY", kw: 132, cc: 1781 },
  { code: "AUE", kw: 150, cc: 2792 },
  { code: "AXJ", kw: 165, cc: 3189 }, { code: "BFH", kw: 177, cc: 3189 }, { code: "BHE", kw: 184, cc: 3189 },
  { code: "AUS", kw: 77, cc: 1598 },
];
const TORQUE_TARGETS = [{ code: "ARY", kw: 132, nm: 235 }];

async function fetchAllRows(table, select) {
  const pageSize = 1000; const rows = []; let from = 0;
  while (true) {
    const { data, error } = await supabase.from(table).select(select).range(from, from + pageSize - 1);
    if (error) throw error;
    rows.push(...(data || []));
    if (!data || data.length < pageSize) break;
    from += pageSize;
  }
  return rows;
}

async function main() {
  const engines = await fetchAllRows("catalog_engines", "id, code, power_kw, display_name, displacement_cc, torque_nm");
  const engineByKey = new Map(engines.map((e) => [`${e.code}@${e.power_kw}`, e]));

  const mismatches = [];
  const dispMatched = [];
  for (const t of DISPLACEMENT_TARGETS) {
    const key = `${t.code}@${t.kw}`;
    const e = engineByKey.get(key);
    if (!e) { mismatches.push(`${key}: no live row`); continue; }
    if (e.displacement_cc !== null) { mismatches.push(`${key}: displacement_cc already non-NULL live (${e.displacement_cc})`); continue; }
    const litres = (Math.round(t.cc / 100) / 10).toFixed(1);
    if (!(e.display_name || "").toLowerCase().includes(litres)) {
      mismatches.push(`${key}: display_name "${e.display_name}" doesn't contain "${litres}" (from ${t.cc}cc) -- sanity check failed`);
      continue;
    }
    dispMatched.push({ ...t, id: e.id });
  }
  const torqueMatched = [];
  for (const t of TORQUE_TARGETS) {
    const key = `${t.code}@${t.kw}`;
    const e = engineByKey.get(key);
    if (!e) { mismatches.push(`${key}: no live row`); continue; }
    if (e.torque_nm !== null) { mismatches.push(`${key}: torque_nm already non-NULL live (${e.torque_nm})`); continue; }
    torqueMatched.push({ ...t, id: e.id });
  }
  if (mismatches.length > 0) {
    throw new Error(`${mismatches.length} mismatches -- aborting, nothing written:\n${mismatches.join("\n")}`);
  }

  const ts = tsNow();
  const outPath = path.join(MIGRATIONS_DIR, `${ts}_fill_engine_displacement_torque.sql`);

  const L = [];
  L.push(`-- Fills missing catalog_engines.displacement_cc (18 engines) and torque_nm (1 engine,`);
  L.push(`-- ARY@132), NULL-only -- never overwrites an existing value.`);
  L.push(`--`);
  L.push(`-- Every target verified live before generating: displacement_cc/torque_nm confirmed`);
  L.push(`-- NULL, and for every displacement target round(cc/100)/10 matches the litre figure in`);
  L.push(`-- that engine's own display_name (e.g. 1781 -> "1.8" matches "1.8T quattro").`);
  L.push(`--`);
  L.push(`-- Generated by scripts/fill/write-engine-displacement-torque-fix-migration.mjs.`);
  L.push(`-- Review-only: NOT run by this session.`);
  L.push(``);
  L.push(`BEGIN;`);
  L.push(``);
  for (const t of dispMatched) {
    L.push(`-- ${t.code}@${t.kw} ("${engineByKey.get(`${t.code}@${t.kw}`).display_name}")`);
    L.push(`UPDATE catalog_engines SET displacement_cc = ${t.cc} WHERE id = '${t.id}'::uuid AND displacement_cc IS NULL;`);
  }
  L.push(``);
  for (const t of torqueMatched) {
    L.push(`-- ${t.code}@${t.kw}`);
    L.push(`UPDATE catalog_engines SET torque_nm = ${t.nm} WHERE id = '${t.id}'::uuid AND torque_nm IS NULL;`);
  }
  L.push(``);
  L.push(`-- Postcondition: exactly ${dispMatched.length} displacement rows + ${torqueMatched.length} torque row changed,`);
  L.push(`-- and 0 engines actually used in catalog_vehicle_configurations still have a NULL`);
  L.push(`-- displacement_cc or torque_nm (this fix was sized to close that gap exactly).`);
  L.push(`DO $$`);
  L.push(`DECLARE disp_n integer;`);
  L.push(`DECLARE torque_n integer;`);
  L.push(`DECLARE used_null_n integer;`);
  L.push(`BEGIN`);
  L.push(`  SELECT count(*) INTO disp_n FROM catalog_engines WHERE id IN (`);
  L.push(dispMatched.map((t) => `    '${t.id}'::uuid`).join(",\n"));
  L.push(`  ) AND displacement_cc IS NOT NULL;`);
  L.push(`  IF disp_n <> ${dispMatched.length} THEN`);
  L.push(`    RAISE EXCEPTION 'Expected ${dispMatched.length} displacement rows filled, found %.', disp_n;`);
  L.push(`  END IF;`);
  L.push(``);
  L.push(`  SELECT count(*) INTO torque_n FROM catalog_engines WHERE id IN (`);
  L.push(torqueMatched.map((t) => `    '${t.id}'::uuid`).join(",\n"));
  L.push(`  ) AND torque_nm IS NOT NULL;`);
  L.push(`  IF torque_n <> ${torqueMatched.length} THEN`);
  L.push(`    RAISE EXCEPTION 'Expected ${torqueMatched.length} torque row filled, found %.', torque_n;`);
  L.push(`  END IF;`);
  L.push(``);
  L.push(`  SELECT count(*) INTO used_null_n FROM catalog_engines e`);
  L.push(`    WHERE (e.displacement_cc IS NULL OR e.torque_nm IS NULL)`);
  L.push(`    AND EXISTS (SELECT 1 FROM catalog_vehicle_configurations c WHERE c.engine_id = e.id);`);
  L.push(`  IF used_null_n <> 0 THEN`);
  L.push(`    RAISE EXCEPTION 'Expected 0 used engines with NULL displacement_cc/torque_nm after this fix, found %.', used_null_n;`);
  L.push(`  END IF;`);
  L.push(`END $$;`);
  L.push(``);
  L.push(`COMMIT;`);

  writeFileSync(outPath, L.join("\n") + "\n");
  console.log(`Wrote ${outPath}`);
  console.log(`  ${dispMatched.length} displacement rows, ${torqueMatched.length} torque row`);
}

main().catch((err) => { console.error(err); process.exit(1); });
