// Writes the guarded, review-only migration fixing catalog_engines.cylinders on 6 engines:
//   ARY@132: NULL -> 'L4'
//   AUE@150, AXJ@165, BHE@184: 'V6' -> 'VR6' (VR6 already allowed live, no constraint change)
//   AGZ@110, AQN@125: 'V5' -> 'VR5' (VR5 NOT in the live catalog_engines_cylinders_check --
//     constraint is extended first, every existing allowed value kept)
//
// Writes a file only -- never executes anything against the DB.

import { createClient } from "@supabase/supabase-js";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const supabase = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY
);

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const MIGRATIONS_DIR = path.join(__dirname, "..", "..", "supabase", "migrations");

function tsNow() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, "0");
  return `${d.getUTCFullYear()}${p(d.getUTCMonth() + 1)}${p(d.getUTCDate())}${p(d.getUTCHours())}${p(d.getUTCMinutes())}${p(d.getUTCSeconds())}`;
}

const TARGETS = [
  { code: "ARY", kw: 132, from: null, to: "L4" },
  { code: "AUE", kw: 150, from: "V6", to: "VR6" },
  { code: "AXJ", kw: 165, from: "V6", to: "VR6" },
  { code: "BHE", kw: 184, from: "V6", to: "VR6" },
  { code: "AGZ", kw: 110, from: "V5", to: "VR5" },
  { code: "AQN", kw: 125, from: "V5", to: "VR5" },
];

const CURRENT_ALLOWED = ["L2", "L3", "L4", "L5", "L6", "V5", "VR6", "V6", "V8", "V10", "V12", "W12", "B4", "B6"];
const NEW_ALLOWED = [...CURRENT_ALLOWED, "VR5"];

async function main() {
  // Verify live state matches what this migration assumes before writing anything.
  const { data: constraintDef, error: cErr } = await supabase.rpc("catalog_check_constraint_def", {
    p_table: "catalog_engines",
    p_column: "cylinders",
  });
  if (cErr) throw cErr;
  const vr5Allowed = /'VR5'/.test(constraintDef ?? "");
  console.log(`Live constraint ${vr5Allowed ? "already allows" : "does NOT allow"} 'VR5'.`);
  for (const allowed of CURRENT_ALLOWED) {
    if (!new RegExp(`'${allowed}'`).test(constraintDef ?? "")) {
      throw new Error(`Live constraint is missing expected existing value '${allowed}' -- it has drifted from what this migration assumes:\n${constraintDef}`);
    }
  }

  const mismatches = [];
  for (const t of TARGETS) {
    const { data: e, error } = await supabase
      .from("catalog_engines")
      .select("id, code, power_kw, cylinders")
      .eq("code", t.code)
      .eq("power_kw", t.kw)
      .maybeSingle();
    if (error) throw error;
    if (!e) { mismatches.push(`${t.code}@${t.kw}: no live row`); continue; }
    if (e.cylinders !== t.from && e.cylinders !== t.to) {
      mismatches.push(`${t.code}@${t.kw}: expected cylinders "${t.from}" (or already-applied "${t.to}"), live is "${e.cylinders}"`);
    }
  }
  if (mismatches.length > 0) {
    throw new Error(`${mismatches.length} mismatches against live data -- aborting:\n${mismatches.join("\n")}`);
  }

  const ts = tsNow();
  const outPath = path.join(MIGRATIONS_DIR, `${ts}_fix_engine_cylinders_vr5_vr6.sql`);

  const L = [];
  L.push(`-- Fixes catalog_engines.cylinders on 6 engines: a plain inline L4 (ARY) was left NULL,`);
  L.push(`-- and 5 V-engines were seeded as the wrong layout code -- VR5/VR6 (narrow-angle,`);
  L.push(`-- single-head VW/Audi "VR" engines) were recorded as the wider V5/V6 layout instead.`);
  L.push(`--   ARY@132: NULL -> 'L4'`);
  L.push(`--   AUE@150, AXJ@165, BHE@184: 'V6' -> 'VR6' (VR6 already allowed live)`);
  L.push(`--   AGZ@110, AQN@125: 'V5' -> 'VR5' (VR5 NOT allowed live -- constraint extended below,`);
  L.push(`--   every existing value kept, only 'VR5' added)`);
  L.push(`--`);
  L.push(`-- Generated by scripts/fill/write-engine-cylinders-fix-migration.mjs, which confirmed`);
  L.push(`-- live: the current catalog_engines_cylinders_check allows ${CURRENT_ALLOWED.join(", ")}`);
  L.push(`-- but not VR5, and each of the 6 target rows currently holds its expected "from" value.`);
  L.push(`--`);
  L.push(`-- Update that JSON file in the same commit as this migration (CLAUDE.md's 8-CHECK-`);
  L.push(`-- constraint rule) -- scripts/catalog-vocabularies.json's`);
  L.push(`-- "catalog_engines.cylinders" entry is updated alongside this file.`);
  L.push(`--`);
  L.push(`-- Review-only: NOT run by this session.`);
  L.push(``);
  L.push(`BEGIN;`);
  L.push(``);
  L.push(`-- Before: show the current state of the 6 target rows and the live constraint.`);
  L.push(`DO $$`);
  L.push(`DECLARE r record;`);
  L.push(`BEGIN`);
  L.push(`  RAISE NOTICE '--- BEFORE ---';`);
  L.push(`  FOR r IN`);
  L.push(`    SELECT code, power_kw, cylinders FROM catalog_engines`);
  L.push(`    WHERE (code, power_kw) IN (`);
  L.push(TARGETS.map((t) => `      ('${t.code}', ${t.kw})`).join(",\n"));
  L.push(`    )`);
  L.push(`    ORDER BY code, power_kw`);
  L.push(`  LOOP`);
  L.push(`    RAISE NOTICE '%@% cylinders = %', r.code, r.power_kw, r.cylinders;`);
  L.push(`  END LOOP;`);
  L.push(`END $$;`);
  L.push(``);
  L.push(`-- Extend the cylinders CHECK constraint to additionally allow 'VR5' -- every existing`);
  L.push(`-- value is kept, nothing removed. VR6 is already allowed, so no constraint change is`);
  L.push(`-- needed for that half of this fix.`);
  L.push(`ALTER TABLE catalog_engines DROP CONSTRAINT IF EXISTS catalog_engines_cylinders_check;`);
  L.push(`ALTER TABLE catalog_engines`);
  L.push(`  ADD CONSTRAINT catalog_engines_cylinders_check`);
  L.push(`  CHECK (cylinders IS NULL OR cylinders IN (`);
  L.push(`    ${NEW_ALLOWED.map((v) => `'${v}'`).join(", ")}`);
  L.push(`  ));`);
  L.push(``);
  for (const t of TARGETS) {
    L.push(`-- ${t.code}@${t.kw}: ${t.from === null ? "NULL" : `'${t.from}'`} -> '${t.to}'`);
    L.push(`UPDATE catalog_engines`);
    L.push(`SET cylinders = '${t.to}'`);
    L.push(
      `WHERE code = '${t.code}' AND power_kw = ${t.kw} AND cylinders ${t.from === null ? "IS NULL" : `= '${t.from}'`};`
    );
  }
  L.push(``);
  L.push(`-- After: show the new state, and assert exactly 6 rows now hold their target value.`);
  L.push(`DO $$`);
  L.push(`DECLARE r record;`);
  L.push(`DECLARE changed_n integer;`);
  L.push(`BEGIN`);
  L.push(`  RAISE NOTICE '--- AFTER ---';`);
  L.push(`  FOR r IN`);
  L.push(`    SELECT code, power_kw, cylinders FROM catalog_engines`);
  L.push(`    WHERE (code, power_kw) IN (`);
  L.push(TARGETS.map((t) => `      ('${t.code}', ${t.kw})`).join(",\n"));
  L.push(`    )`);
  L.push(`    ORDER BY code, power_kw`);
  L.push(`  LOOP`);
  L.push(`    RAISE NOTICE '%@% cylinders = %', r.code, r.power_kw, r.cylinders;`);
  L.push(`  END LOOP;`);
  L.push(``);
  L.push(`  SELECT count(*) INTO changed_n FROM catalog_engines WHERE (code, power_kw, cylinders) IN (`);
  L.push(TARGETS.map((t) => `    ('${t.code}', ${t.kw}, '${t.to}')`).join(",\n"));
  L.push(`  );`);
  L.push(`  IF changed_n <> 6 THEN`);
  L.push(`    RAISE EXCEPTION 'Expected exactly 6 engines updated to their target cylinders value, found %.', changed_n;`);
  L.push(`  END IF;`);
  L.push(`END $$;`);
  L.push(``);
  L.push(`COMMIT;`);

  writeFileSync(outPath, L.join("\n") + "\n");
  console.log(`Wrote ${outPath}`);
}

main().catch((err) => { console.error(err); process.exit(1); });
